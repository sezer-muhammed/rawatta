"""Write THIRD-PARTY-LICENSES.md: the licence texts of every Rust crate compiled into the rawatta binary.

The binary links its Rust dependencies statically, and MIT, ISC, BSD and Zlib require their notices to
accompany binary copies, so the Docker image ships this file in /opt/rawatta/. The crate list is the
normal (non-dev) dependency graph of rawatta-cli on x86_64-unknown-linux-gnu from `cargo metadata`,
build dependencies and proc-macros included (their code runs at build time; listing them costs nothing).
The texts are the LICENSE*/COPYING*/NOTICE* files of each crate's source in the cargo registry.

    python3 scripts/third_party_licenses.py              # writes THIRD-PARTY-LICENSES.md
    python3 scripts/third_party_licenses.py --check      # exits 1 if the committed file is out of date

Needs cargo and the crate sources (run `cargo fetch --locked` first). Prints the crates whose source has
no licence file; their licence is still listed by its SPDX expression.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-LICENSES.md"
TARGET = "x86_64-unknown-linux-gnu"
PATTERNS = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE")


def metadata() -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def graph(meta: dict, root_name: str) -> list[dict]:
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(i for i, p in pkgs.items() if p["name"] == root_name and p["source"] is None)
    seen, todo = set(), [root]
    while todo:
        i = todo.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
                todo.append(d["pkg"])
    # Workspace crates are this repository's own code (LICENSE, LICENSE-VGGT-OMEGA).
    return sorted((pkgs[i] for i in seen if pkgs[i]["source"] is not None), key=lambda p: (p["name"], p["version"]))


def licence_files(pkg: dict) -> list[Path]:
    d = Path(pkg["manifest_path"]).parent
    files = [f for f in sorted(d.iterdir()) if f.is_file() and f.name.upper().startswith(PATTERNS)]
    if pkg.get("license_file"):
        f = d / pkg["license_file"]
        if f.is_file() and f not in files:
            files.append(f)
    return files


def render(pkgs: list[dict]) -> tuple[str, list[str]]:
    missing = []
    lines = [
        "# Third-party licences of the rawatta binary",
        "",
        "The `rawatta` binary statically links the Rust crates below (versions from `Cargo.lock`, target",
        f"`{TARGET}`). This file holds their licence texts as published in each crate's source; it is",
        "generated by `scripts/third_party_licenses.py` and ships in the Docker image as",
        "`/opt/rawatta/THIRD-PARTY-LICENSES.md`. The rawatta code itself is under `LICENSE` (Apache-2.0) and",
        "`LICENSE-VGGT-OMEGA` (FAIR Noncommercial Research License, crates/vggt-omega), with `LICENSE-DINOV3`",
        "for the DINOv3 backbone code it ports; see `NOTICE`.",
        "",
        "| Crate | Version | Licence |",
        "|---|---|---|",
    ]
    for p in pkgs:
        lic = p.get("license") or ("see " + p["license_file"] if p.get("license_file") else "unspecified")
        lines.append(f"| {p['name']} | {p['version']} | {lic} |")
    for p in pkgs:
        lines += ["", f"## {p['name']} {p['version']}", ""]
        lic = p.get("license") or "unspecified"
        lines.append(f"Licence: {lic}" + (f". Source: {p['repository']}" if p.get("repository") else ""))
        files = licence_files(p)
        if not files:
            missing.append(f"{p['name']} {p['version']} ({lic})")
            lines += ["", "The crate's source carries no licence file; its licence is the SPDX expression above."]
        for f in files:
            text = f.read_text(encoding="utf-8", errors="replace").rstrip()
            lines += ["", f"### {f.name}", "", "````text", text, "````"]
    return "\n".join(lines) + "\n", missing


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if THIRD-PARTY-LICENSES.md is out of date")
    a = ap.parse_args()
    text, missing = render(graph(metadata(), "rawatta-cli"))
    for m in missing:
        print(f"no licence file in the crate source: {m}", file=sys.stderr)
    if a.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} is out of date: run scripts/third_party_licenses.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
